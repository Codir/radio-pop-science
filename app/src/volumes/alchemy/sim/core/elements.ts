const BRACKETED = /^(.+) \((.+)\)$/;

export const ELEMENTS: readonly ElementInfo[] = NAMES.map((full, i) => {
  const symbol = SOURCE_SYMBOLS[i]!;
  const m = BRACKETED.exec(full);
  return m ? { z: i + 1, symbol, nameUk: m[1]!, substanceUk: m[2]! } : { z: i + 1, symbol, nameUk: full };
});

export function elementByZ(z: number): ElementInfo | undefined {
  return Number.isInteger(z) ? ELEMENTS[z - 1] : undefined;
}

/** «Аурум (золото)», «Гелій»; empty string for an unknown Z. */
export function elementName(z: number): string {
  const e = elementByZ(z);
  if (!e) return '';
  return e.substanceUk ? `${e.nameUk} (${e.substanceUk})` : e.nameUk;
}
